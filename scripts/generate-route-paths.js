const fs = require('fs');
const path = require('path');
const { readBounds } = require('./lib/serviceArea');

const HEADERS = { 'User-Agent': 'TriwayDemo/1.0 (student project)' };
const B = readBounds();
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const ONLY = ['cathedral-taktak', 'ynares-city-hall'];

// Where the demo driver starts, per route id, about 0.5 to 2 km before the pickup.
// A place name (searched with Photon) or exact [longitude, latitude].
// A HUMAN fills this in. Leave a route out to skip its approach.
const APPROACH_FROM = {
  'cathedral-taktak': [121.18547, 14.59495],   // San Isidro Barangay Hall, unverified as a terminal
  'ynares-city-hall': [121.16766, 14.59468],   // Hinulugang Taktak, unverified as a terminal
};

// Manual fixes. Coordinates are [longitude, latitude].
// origin / destination: use when Photon picks the wrong place.
// via: waypoints to force the path through roads tricycles actually use.
const OVERRIDES = {
  // 'cogeo-boso-boso': { via: [[121.2, 14.62]] },
};

async function geocode(name) {
  const url = `https://photon.komoot.io/api/?q=${encodeURIComponent(name + ', Antipolo, Rizal')}&limit=1&lang=en&bbox=${B.photonBbox}`;
  const json = await (await fetch(url, { headers: HEADERS })).json();
  const f = json.features && json.features[0];
  if (!f) return null;
  const p = f.properties;
  return { coords: f.geometry.coordinates, label: [p.name, p.street, p.city].filter(Boolean).join(', ') };
}

async function route(points) {
  const coords = points.map((c) => c.join(',')).join(';');
  const url = `https://router.project-osrm.org/route/v1/driving/${coords}?overview=full&geometries=polyline`;
  const json = await (await fetch(url, { headers: HEADERS })).json();
  const r = json.routes && json.routes[0];
  return r ? { polyline: r.geometry, km: r.distance / 1000 } : null;
}

(async () => {
  const source = fs.readFileSync(path.join(__dirname, '../data/routes.ts'), 'utf8');
  const routes = [...source.matchAll(
    /id: '([^']+)'[^\n]*?origin: '([^']+)', destination: '([^']+)', distanceKm: ([\d.]+)/g
  )].map(([, id, origin, destination, km]) => ({ id, origin, destination, km: Number(km) }));

  const trip = {};
  const approach = {};

  for (const r of routes) {
    if (!ONLY.includes(r.id)) {
      console.log(`${r.id}\n  skipped (not a demo route)`);
      continue;
    }

    const o = OVERRIDES[r.id] || {};
    const a = o.origin ? { coords: o.origin, label: 'override' } : await geocode(r.origin);
    await sleep(1100);
    const b = o.destination ? { coords: o.destination, label: 'override' } : await geocode(r.destination);
    await sleep(1100);
    if (!a || !b) { console.error(`FAILED ${r.id}: place not found (${!a ? r.origin : r.destination})`); continue; }

    const res = await route([a.coords, ...(o.via || []), b.coords]);
    await sleep(1100);
    if (!res) { console.error(`FAILED ${r.id}: no route`); continue; }

    trip[r.id] = res.polyline;
    console.log(`${r.id}\n  from "${r.origin}" -> ${a.label}\n  to   "${r.destination}" -> ${b.label}\n  trip ${res.km.toFixed(1)} km (your data: ${r.km} km)`);

    const from = APPROACH_FROM[r.id];
    if (!from) { console.log('  approach: none set, the demo will skip the pickup path for this route'); continue; }

    const s = Array.isArray(from) ? { coords: from, label: 'override' } : await geocode(from);
    if (!Array.isArray(from)) await sleep(1100);
    if (!s) { console.warn(`  approach: could not find "${from}"`); continue; }

    const ap = await route([s.coords, a.coords]);
    await sleep(1100);
    if (!ap) { console.warn('  approach: no route found'); continue; }
    if (ap.km < 0.15) { console.warn(`  approach: only ${(ap.km * 1000).toFixed(0)} m, too short, skipped`); continue; }

    approach[r.id] = ap.polyline;
    console.log(`  approach from ${s.label}: ${ap.km.toFixed(1)} km`);
  }

  const file =
    `// Generated by scripts/generate-route-paths.js. Do not edit by hand.\n` +
    `export const routePaths: Record<string, string> = ${JSON.stringify(trip, null, 2)};\n\n` +
    `export const approachPaths: Record<string, string> = ${JSON.stringify(approach, null, 2)};\n`;
  fs.writeFileSync(path.join(__dirname, '../data/routePaths.ts'), file);
  console.log('\nWrote data/routePaths.ts');
})();
